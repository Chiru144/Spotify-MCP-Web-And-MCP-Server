"""Playlist generators: vibe, radio, era and time capsule.

Each generator previews its picks by default and only creates a playlist when `create=True`.
They use the local library cache where it helps (songs you already like) and search otherwise.
"""
import random
from typing import Optional, List, Dict, Any
from mcp.types import ToolAnnotations
from tools.core import mcp, get_spotify_client, _format_duration
from tools import discovery
from tools.library_cache import load_library, query_tracks

GENERATOR_ANNOTATIONS = ToolAnnotations(read_only_hint=False, destructive_hint=False, idempotent_hint=False, open_world_hint=True)


def _not_synced() -> str:
    return "Your library isn't cached yet. Run spotify_sync_library first, or pass from_library=False to pick from all of Spotify."


def _finish(sp, title: str, tracks: List[Dict[str, Any]], create: bool, name: Optional[str],
            public: bool, notes: List[str] = ()) -> str:
    """Preview the picks, or create the playlist and add them when `create` is True."""
    if not tracks:
        return f"{title}: no tracks found."
    lines = [f"{title} ({len(tracks)} tracks):"]
    lines.extend(notes)
    for i, t in enumerate(tracks, 1):
        artists = ", ".join(a.get("name") or "Unknown" for a in t.get("artists", []))
        vibe = f" [vibe: {', '.join(t['vibe_genres'])}]" if t.get("vibe_genres") else ""
        lines.append(f"{i}. {t.get('name')} - {artists} ({_format_duration(t.get('duration_ms'))}){vibe} (URI: {t.get('uri')})")
    if not create:
        lines.append("\nPreview only. Call again with create=True to save it as a playlist.")
        return "\n".join(lines)

    playlist = sp.current_user_playlist_create(name or title, public=public,
                                               description=f"{title} - generated by Spotify MCP")
    uris = [t["uri"] for t in tracks if t.get("uri")]
    for i in range(0, len(uris), 100):
        sp.playlist_add_items(playlist["id"], uris[i:i + 100])
    lines.insert(1, f"Created playlist '{playlist.get('name', name or title)}': {(playlist.get('external_urls') or {}).get('spotify', playlist.get('id'))}")
    return "\n".join(lines)


@mcp.tool(annotations=GENERATOR_ANNOTATIONS)
def spotify_vibe_playlist(
    mood: Optional[str] = None,
    target_energy: Optional[float] = None,
    target_valence: Optional[float] = None,
    genres: Optional[List[str]] = None,
    from_library: bool = True,
    limit: int = 30,
    create: bool = False,
    name: Optional[str] = None,
    public: bool = False
) -> str:
    """Build a playlist for a mood or an energy/valence target, from songs you already like (cached library) or from all of Spotify.
    Spotify no longer provides audio features, so each song's vibe is estimated from the genres its artist appears under.

    Args:
        mood: Optional preset ('happy', 'sad', 'chill', 'energetic', 'focus', 'party', 'dark', 'romantic', 'workout').
        target_energy: Optional intensity 0.0-1.0 (overrides the mood's).
        target_valence: Optional positivity 0.0-1.0 (overrides the mood's).
        genres: Optional genres (max 4). With from_library, your songs are checked against these instead of the genres closest to the vibe; without it, songs are picked from these genres.
        from_library: Pick from your cached Liked Songs and playlists (default: True; run spotify_sync_library first).
        limit: Number of tracks (default: 30, max: 100).
        create: Save the result as a new playlist (default: False = preview only).
        name: Playlist name when creating (default: generated from the mood).
        public: Whether the created playlist is public (default: False).
    """
    try:
        target = discovery.vibe_target(mood, target_energy, target_valence)
        if target is None:
            return "Give a mood (e.g. 'chill', 'workout') or a target_energy / target_valence between 0 and 1."
        limit = max(1, min(limit, 100))
        title = f"{(mood or 'Custom').title()} Vibe"
        sp = get_spotify_client()
        if from_library:
            library = load_library()
            if not library:
                return _not_synced()
            genre_list = [genres] if isinstance(genres, str) else genres
            report: Dict[str, Any] = {}
            tracks = discovery.pick_by_vibe(sp, library.get("tracks", []), target, limit, genres=genre_list, report=report)
            note = (f"Estimated a vibe for {report['placed']} of {len(library.get('tracks', []))} cached tracks "
                    f"(genre searches: {', '.join(report['genres'])}; plus words in track, album and playlist names). "
                    "Songs without an estimate were skipped. Naming your playlists by mood (e.g. 'Gym', 'Chill', 'Sad') improves this.")
        else:
            genre_list = ([genres] if isinstance(genres, str) else genres) or discovery.vibe_genres(target)
            tracks = discovery.genre_tracks(sp, genre_list, limit)
            note = f"Picked from Spotify genres: {', '.join(genre_list)}."
        return _finish(sp, title, tracks, create, name, public, [note])
    except Exception as e:
        return f"Error building vibe playlist: {str(e)}"


@mcp.tool(annotations=GENERATOR_ANNOTATIONS)
def spotify_radio_playlist(
    seed: str,
    limit: int = 30,
    create: bool = False,
    name: Optional[str] = None,
    public: bool = False
) -> str:
    """Build an artist radio playlist: the seed artist's songs mixed with songs by the artists they collaborate with.

    Args:
        seed: Artist name, ID, URI or link, or a track URI/link (its lead artist is used).
        limit: Number of tracks (default: 30, max: 100).
        create: Save the result as a new playlist (default: False = preview only).
        name: Playlist name when creating (default: '<Artist> Radio').
        public: Whether the created playlist is public (default: False).
    """
    try:
        sp = get_spotify_client()
        limit = max(1, min(limit, 100))
        artist = None
        if "track" in seed:
            track = sp.track(seed.split("?")[0].rstrip("/").split("/")[-1].split(":")[-1])
            lead = (track.get("artists") or [{}])[0]
            artist = sp.artist(lead["id"]) if lead.get("id") else None
        else:
            artist = discovery.find_artist(sp, seed)
        if not artist:
            return f"Artist '{seed}' not found on Spotify."

        own = discovery.artist_tracks(sp, artist, limit=20)
        peers = discovery.collaborators(sp, artist, own, limit=6)
        per_peer = max(1, -(-(limit - limit // 3) // max(1, len(peers))))
        picks = own[:limit // 3] + discovery.tracks_by_artists(sp, peers, per_artist=per_peer,
                                                              exclude=[t["uri"] for t in own[:limit // 3]])
        random.shuffle(picks)
        note = f"Collaborators: {', '.join(p.get('name', '?') for p in peers) or 'none found'}."
        return _finish(sp, f"{artist['name']} Radio", picks[:limit], create, name, public, [note])
    except Exception as e:
        return f"Error building radio playlist: {str(e)}"


@mcp.tool(annotations=GENERATOR_ANNOTATIONS)
def spotify_era_playlist(
    start_year: int,
    end_year: Optional[int] = None,
    genres: Optional[List[str]] = None,
    from_library: bool = False,
    limit: int = 30,
    create: bool = False,
    name: Optional[str] = None,
    public: bool = False
) -> str:
    """Build a playlist of songs released in a year range (e.g. 1990-1999), optionally limited to genres or to your cached library.

    Args:
        start_year: First release year (e.g. 1990).
        end_year: Last release year (default: same as start_year).
        genres: Optional genres for Spotify search (e.g. ['rock', 'pop']); ignored with from_library.
        from_library: Pick only from your cached Liked Songs and playlists (default: False).
        limit: Number of tracks (default: 30, max: 100).
        create: Save the result as a new playlist (default: False = preview only).
        name: Playlist name when creating (default: generated from the years).
        public: Whether the created playlist is public (default: False).
    """
    try:
        end_year = end_year or start_year
        lo, hi = min(start_year, end_year), max(start_year, end_year)
        limit = max(1, min(limit, 100))
        title = f"{lo} Hits" if lo == hi else f"{lo}-{hi} Era"
        sp = get_spotify_client()
        if from_library:
            library = load_library()
            if not library:
                return _not_synced()
            tracks = query_tracks(library, year_from=lo, year_to=hi)
            random.shuffle(tracks)
            tracks = tracks[:limit]
        else:
            genre_list = [genres] if isinstance(genres, str) else genres
            tracks = discovery.era_tracks(sp, lo, hi, genre_list, limit)
        return _finish(sp, title, tracks, create, name, public)
    except Exception as e:
        return f"Error building era playlist: {str(e)}"


@mcp.tool(annotations=GENERATOR_ANNOTATIONS)
def spotify_time_capsule_playlist(
    year: Optional[int] = None,
    limit: int = 30,
    create: bool = False,
    name: Optional[str] = None,
    public: bool = False
) -> str:
    """Build a time capsule playlist: the songs you saved in a given year (from your cached library),
    or, without a year, your all-time top tracks.

    Args:
        year: Optional year you saved/added the songs (e.g. 2021). Needs spotify_sync_library first.
        limit: Number of tracks (default: 30, max: 50 without a year, 100 with one).
        create: Save the result as a new playlist (default: False = preview only).
        name: Playlist name when creating (default: 'Time Capsule <year>' or 'All-Time Favourites').
        public: Whether the created playlist is public (default: False).
    """
    try:
        sp = get_spotify_client()
        if year is not None:
            library = load_library()
            if not library:
                return "Your library isn't cached yet. Run spotify_sync_library first."
            tracks = [t for t in library.get("tracks", []) if (t.get("added_at") or "").startswith(str(year))]
            tracks.sort(key=lambda t: t.get("added_at") or "")
            return _finish(sp, f"Time Capsule {year}", tracks[:max(1, min(limit, 100))], create, name, public,
                           [f"Songs you saved or added to your playlists in {year}, oldest first."])
        items = sp.current_user_top_tracks(limit=max(1, min(limit, 50)), time_range="long_term").get("items", [])
        return _finish(sp, "All-Time Favourites", items, create, name, public,
                       ["Your top tracks over Spotify's long-term window (several years)."])
    except Exception as e:
        return f"Error building time capsule playlist: {str(e)}"
